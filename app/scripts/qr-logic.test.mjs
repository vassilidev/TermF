const asRows = (dark) => dark.map((row) => row.map((d) => (d ? "1" : "0")).join(""));

/** The mask a code was drawn with, from the first copy of its format bits; its level must be M. */
function maskOf(rows) {
  const at = (x, y) => (rows[y][x] === "1" ? 1 : 0);
  const cells = [[8, 0], [8, 1], [8, 2], [8, 3], [8, 4], [8, 5], [8, 7], [8, 8], [7, 8], [5, 8], [4, 8], [3, 8], [2, 8], [1, 8], [0, 8]];
  const bits = cells.reduce((acc, [x, y], i) => acc | (at(x, y) << i), 0) ^ 0x5412;
  assert.equal(bits >> 13, 0, "level M");
  return (bits >> 10) & 7;
}

test("qr: the same modules as macOS's encoder, mask for mask, versions 1, 4 and 8", () => {
  for (const { text, rows } of VECTORS) {
    assert.deepEqual(asRows(qr(text, maskOf(rows))), rows, text);
  }
});

test("qr: picks a mask by the standard's penalty, the lowest", () => {
  const text = VECTORS[1].text;
  const chosen = qr(text);
  const scores = [0, 1, 2, 3, 4, 5, 6, 7].map((m) => penalty(qr(text, m)));
  assert.equal(penalty(chosen), Math.min(...scores));
});

test("qr: the smallest version that holds the text, and none past version 10", () => {
  assert.equal(qr("").length, 21);
  assert.equal(qr("a".repeat(14)).length, 21);
  assert.equal(qr("a".repeat(15)).length, 25);
  assert.equal(qr("a".repeat(213)).length, 57);
  assert.throws(() => qr("a".repeat(214)), /too long/);
  assert.ok(fits("a".repeat(213)) && !fits("a".repeat(214)));
  // The longest link TermF accepts (termf_core::remote::LINK_MAX) still fits.
  assert.ok(fits(`https://claude.ai/code/${"a".repeat(190)}`));
  // UTF-8: "é" takes two bytes.
  assert.equal(qr("é".repeat(7)).length, 21);
  assert.equal(qr("é".repeat(8)).length, 25);
});

test("qrPath: one unit square per dark module, past the quiet zone", () => {
  assert.equal(qrPath([[true, false], [false, true]], 4), "M4 4h1v1h-1zM5 5h1v1h-1z");
});
